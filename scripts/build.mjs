// Build the app and the worker:
// 1. bundle the React front end (web/src) into app.js and put web/styles.css into web/index.html,
// 2. inline those plus the static files in public/ into src/assets.js (generated),
// 3. bundle the worker into dist/worker.js.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { build } from 'esbuild';

const TYPES = { html: 'text/html; charset=utf-8', js: 'text/javascript; charset=utf-8', webmanifest: 'application/manifest+json', png: 'image/png', svg: 'image/svg+xml' };
const assets = {};
for (const f of readdirSync('public')) {
  const ext = f.split('.').pop();
  const bin = ext === 'png';
  const body = bin ? readFileSync('public/' + f).toString('base64') : readFileSync('public/' + f, 'utf8');
  assets['/' + f] = { type: TYPES[ext] || 'application/octet-stream', body, b64: bin, cache: bin ? 'public, max-age=604800' : 'no-cache' };
}

const app = await build({
  entryPoints: ['web/src/main.jsx'], bundle: true, write: false, format: 'iife', target: 'es2020',
  jsx: 'automatic', minify: true, legalComments: 'none', define: { 'process.env.NODE_ENV': '"production"' },
});
assets['/app.js'] = { type: TYPES.js, body: app.outputFiles[0].text, cache: 'no-cache' };
const html = readFileSync('web/index.html', 'utf8').replace('/*STYLES*/', () => readFileSync('web/styles.css', 'utf8'));
assets['/'] = { type: TYPES.html, body: html, cache: 'no-cache' };

// Write only when something changed, so `wrangler dev` (which watches src/) doesn't rebuild in a loop.
const out = '// generated by scripts/build.mjs\nexport const ASSETS = ' + JSON.stringify(assets) + ';\n';
if (!existsSync('src/assets.js') || readFileSync('src/assets.js', 'utf8') !== out) writeFileSync('src/assets.js', out);
mkdirSync('dist', { recursive: true });
await build({ entryPoints: ['src/worker.js'], bundle: true, format: 'esm', target: 'es2022', outfile: 'dist/worker.js', banner: { js: '// Baby Care Log worker (generated by scripts/build.mjs)' } });
console.log(`built dist/worker.js (app.js ${Math.round(assets['/app.js'].body.length / 1024)} KB)`);
