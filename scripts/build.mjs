// Inline public/ into src/assets.js, then bundle everything into dist/worker.js (one file to paste into Cloudflare).
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { build } from 'esbuild';
const TYPES = { html: 'text/html; charset=utf-8', js: 'text/javascript; charset=utf-8', webmanifest: 'application/manifest+json', png: 'image/png', svg: 'image/svg+xml' };
const assets = {};
for (const f of readdirSync('public')) {
  const ext = f.split('.').pop();
  const bin = ext === 'png';
  const body = bin ? readFileSync('public/' + f).toString('base64') : readFileSync('public/' + f, 'utf8');
  const key = f === 'index.html' ? '/' : '/' + f;
  assets[key] = { type: TYPES[ext] || 'application/octet-stream', body, b64: bin, cache: bin ? 'public, max-age=604800' : 'no-cache' };
}
writeFileSync('src/assets.js', '// generated by scripts/build.mjs\nexport const ASSETS = ' + JSON.stringify(assets) + ';\n');
mkdirSync('dist', { recursive: true });
await build({ entryPoints: ['src/worker.js'], bundle: true, format: 'esm', target: 'es2022', outfile: 'dist/worker.js', banner: { js: '// Baby Care Log — paste this whole file into your Cloudflare Worker and deploy.' } });
console.log('built dist/worker.js');
